def to_css(name: str, art: str) -> str:
    rows = art.strip('\n').split('\n')
    shadows = [
        f'{x}em {y}em {PALETTE[ch]}'
        for y, row in enumerate(rows)
        for x, ch in enumerate(row)
        if ch in PALETTE
    ]
    return f'.px-{name}{{box-shadow:{",".join(shadows)}}}'


