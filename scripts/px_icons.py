    print('/* 자동 생성: scripts/px_icons.py — 직접 수정하지 말 것 */')
    print('.px{position:relative;width:1em;height:1em;font-size:4px;display:block}')
    for name, art in SPRITES.items():
        print(to_css(name, art))
