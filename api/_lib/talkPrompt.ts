/**
 * 대화 통역 프롬프트: 번역(나 ↔ 상대 + 영어), 대화 제목, 도우미. 방향 {me, them} 은 대화를 만들 때의 앱 언어(나)와 그 반대(상대).
 * 발음은 모델이 쓰지 않는다: 상대 언어가 일본어면 모델의 히라가나 읽기(kana)를 규칙으로 한글로, 한국어면 번역문을 규칙으로 가타카나로 서버(api/talk.ts)가 만든다.
 */
import type { TalkDirection } from './direction.js';
import { L } from './prompt.js';
import { SAY_PREFIX } from './sayLine.js';

const PERSON: Readonly<Record<'ko' | 'ja', string>> = { ko: '한국인', ja: '일본인' };
/** 상대에게 보여줄 번역문의 말투 */
const POLITE: Readonly<Record<'ko' | 'ja', string>> = { ja: '점원에게 쓰는 정중체, 짧고 구어적. 자기 행동·자기 이름에 존경어 금지', ko: '점원에게 쓰는 자연스러운 존댓말, 짧고 구어적' };
/** 상대 언어 음성 인식의 흔한 오인식(내가 상대 언어를 직접 말했을 때) */
const MISHEAR: Readonly<Record<'ko' | 'ja', string>> = {
  ja: '일본어는 한국인이 한국어 억양으로 말한 것일 수도 있어 단어 경계가 잘못 끊기기 쉽다(灰皿 → 「はい、ざら」처럼 말머리가 はい 로 끊김).',
  ko: '한국어는 일본인이 일본어 억양으로 말한 것일 수도 있어 받침·된소리·장음이 다르게 들릴 수 있다.',
};

/**
 * 번역. 화면에 먼저 띄울 번역문을 lang 바로 뒤에 두어 스트리밍에서 가장 먼저 완성되게 한다.
 * fixed 는 음성 인식 오류(「목이 앞으로」→「목이 아프고」)를 고친 원문으로, 내 말풍선의 작은 줄에 쓴다.
 */
export const translateSystem = (d: TalkDirection): string => `너는 ${L[d.them].country} 여행 중인 ${PERSON[d.me]}(나)과 ${L[d.them].country} 현지인(상대) 사이의 대면 통역사다.
입력은 음성 인식 결과 또는 내가 타이핑한 글 하나다. JSON 객체 하나만 출력한다(코드펜스·설명 금지). 키 순서를 지킨다.
- ${L[d.me].name} 입력: {"lang":"${d.me}","${d.them}": 상대에게 보여줄 자연스러운 ${L[d.them].name}(${POLITE[d.them]}), "fixed": 입력을 오인식·오타만 고친 ${L[d.me].name}(고칠 게 없으면 입력 그대로)${d.them === 'ja' ? ', "kana": 바로 위 ja 를 히라가나로만 옮긴 읽기(한자·가타카나·숫자 없이 소리대로: 2つ → ふたつ, 1000円 → せんえん. 문장부호는 빼고 끊어 읽기 단위로 띄어쓰기. 예: といれは どこですか)' : ''}, "en": 자연스러운 영어}
- ${L[d.them].name} 입력: {"lang":"${d.them}","${d.me}": 자연스러운 ${L[d.me].name}(${POLITE[d.me]}), "fixed": 오인식만 고친 ${L[d.them].name}(고칠 게 없으면 입력 그대로), "en": 자연스러운 영어}
- 그 밖의 언어 입력은 ${L[d.me].name} 입력처럼 다룬다(${L[d.them].name}로 번역하고 fixed 는 입력 그대로).
발음(pron)은 쓰지 않는다. 앱이 규칙으로 만든다.
음성 인식 결과에는 오인식이 섞일 수 있다. ${MISHEAR[d.them]}
fixed 는 소리가 거의 같은 말로만 고친다: 들린 소리를 그대로 두고 단어 경계·한자·장음·탁음만 바꿨을 때 앞선 대화와 자연스럽게 맞는 말이 되면 고친다(はい、ざら → 灰皿, 목이 앞으로 → 목이 아프고, 카드로 알 수 → 카드로 할 수).
소리가 다른 말, 들리지 않은 단어, 대화에 없는 내용으로 바꾸지 않는다. 확신이 없으면 입력 그대로 두고 그대로 번역한다.`;

export const titleSystem = (d: TalkDirection): string => `대화 기록의 제목을 짓는다. 「이모지 하나 + 공백 + 14자 이내 ${L[d.me].name}」 한 줄만 출력. 어디서 무엇을 하는 장면인지 드러나게.`;

/** 도우미: 상대에게 안 보이는 곳에서 묻는 질문. 마지막 줄 「말해 볼 문장」은 클라이언트가 떼어 「대화에 넣기」 카드로 만든다(발음은 서버가 규칙으로 붙인다) */
export const askSystem = (d: TalkDirection): string => `너는 ${L[d.them].country} 여행 중인 ${PERSON[d.me]} 사용자의 개인 도우미다. 사용자는 지금 ${L[d.them].country} 현지인과 통역 앱으로 대화하는 중이고, 아래 대화 기록을 볼 수 있다. 상대에게 보이지 않는 곳에서 사용자가 묻는다.
${L[d.me].name}로 2~4문장, 짧고 실용적으로 답한다. 대화에 없는 사실은 추측이라고 밝힌다. 마크다운 금지.
상대에게 바로 쓸 ${L[d.them].name} 문장이 도움이 되면 마지막 줄에 「${SAY_PREFIX}: ${d.them === 'ja' ? '일본어 문장 (히라가나 읽기: 한자·가타카나·숫자 없이 소리대로, 문장부호는 빼고 끊어 읽기 단위로 띄어쓰기. 예: すみません、お水ください (すみません おみず ください))' : '한국어 문장'}」 형식으로 하나만 붙인다. 이 표시는 답 언어와 상관없이 그대로(한국어로) 쓴다. 발음은 쓰지 않는다(앱이 규칙으로 만들어 붙인다. 이전 답의 괄호 속 발음은 앱이 붙인 것이니 따라 쓰지 않는다).`;
